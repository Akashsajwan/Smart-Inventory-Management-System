def get_demo_products(store_type="electronics"):
    """Return a list of 10 authentic demo warehouse products for the given store category.

    Args:
        store_type (str): 'electronics', 'grocery', 'clothing', or 'general'.

    Returns:
        list[dict]: Deep copy list of 10 product definitions.
    """
    key = str(store_type or "electronics").lower().strip()
    catalog = DEMO_PRODUCTS_BY_STORE.get(key, DEMO_PRODUCTS_BY_STORE["electronics"])
    return [dict(p) for p in catalog]


